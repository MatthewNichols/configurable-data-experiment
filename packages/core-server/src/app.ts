import express, { Router, type Express } from 'express';
import { existsSync } from 'node:fs';
import { Kysely, PostgresDialect } from 'kysely';
import pg from 'pg';
import { findEntityByPath, type Registry } from '@cde/sdk';
import type { Logger, ServerContext, ServerModule } from '@cde/sdk/server';
import { EntityService } from './entities/service.ts';
import { errorHandler, HttpError } from './errors.ts';
import { ExtensionPoints } from './extensions.ts';
import type { SearchParams } from './search/builder.ts';

export interface InstallOptions {
  registry: Registry;
  /** the customer's generated Prisma client instance */
  prisma: any;
  databaseUrl: string;
  /** module name -> server module, generated by the assembler */
  modules: Record<string, ServerModule>;
  webDist?: string;
}

export interface Install {
  app: Express;
  service: EntityService;
  db: Kysely<any>;
  prisma: any;
  registry: Registry;
  close(): Promise<void>;
}

const logger = (prefix: string): Logger => ({
  info: (m, ...a) => console.log(`[${prefix}] ${m}`, ...a),
  warn: (m, ...a) => console.warn(`[${prefix}] ${m}`, ...a),
  error: (m, ...a) => console.error(`[${prefix}] ${m}`, ...a),
});

export async function createInstall(opts: InstallOptions): Promise<Install> {
  const { registry, prisma } = opts;
  // Postgres `date` values stay 'YYYY-MM-DD' strings (node-pg would turn them into local-midnight Dates).
  const types = { getTypeParser: (oid: number, format?: any) => (oid === 1082 ? (v: string) => v : pg.types.getTypeParser(oid, format)) };
  const pool = new pg.Pool({ connectionString: opts.databaseUrl, types } as pg.PoolConfig);
  const db = new Kysely<any>({ dialect: new PostgresDialect({ pool }) });
  const ext = new ExtensionPoints();
  const service = new EntityService(registry, prisma, db, ext);

  const app = express();
  app.set('query parser', 'extended');
  app.use(express.json());

  app.get('/api/health', (_req, res) => {
    res.json({ ok: true, customer: registry.customer.name });
  });
  app.get('/api/meta', (_req, res) => {
    res.json(registry);
  });

  for (const [name, mod] of Object.entries(opts.modules)) {
    const router = Router();
    const ctx: ServerContext = {
      module: name,
      registry,
      prisma,
      db,
      router,
      logger: logger(name),
      hooks: {
        beforeSave: (entity, fn) => ext.add('beforeSave', entity, fn),
        afterSave: (entity, fn) => ext.add('afterSave', entity, fn),
        beforeDelete: (entity, fn) => ext.add('beforeDelete', entity, fn),
      },
      search: {
        extend: (entity, fn) => {
          if (!ext.search.has(entity)) ext.search.set(entity, new Map());
          ext.search.get(entity)!.set(name, fn);
        },
      },
      enrich: (entity, fn) => ext.add('enrich', entity, fn),
    };
    await mod.register(ctx);
    app.use(`/api/modules/${name}`, router);
  }

  const entityFromPath = (p: string) => {
    const e = findEntityByPath(registry, p);
    if (!e) throw new HttpError(404, `Unknown entity path ${p}`);
    return e.name;
  };

  app.get('/api/:entity', async (req, res) => {
    res.json(await service.list(entityFromPath(req.params.entity), req.query as SearchParams));
  });
  app.get('/api/:entity/:id', async (req, res) => {
    res.json(await service.get(entityFromPath(req.params.entity), req.params.id));
  });
  app.post('/api/:entity', async (req, res) => {
    res.status(201).json(await service.create(entityFromPath(req.params.entity), req.body));
  });
  app.put('/api/:entity/:id', async (req, res) => {
    res.json(await service.update(entityFromPath(req.params.entity), req.params.id, req.body));
  });
  app.delete('/api/:entity/:id', async (req, res) => {
    await service.remove(entityFromPath(req.params.entity), req.params.id);
    res.status(204).end();
  });
  app.use('/api', (_req, _res, next) => next(new HttpError(404, 'Not found')));

  if (opts.webDist && existsSync(opts.webDist)) {
    app.use(express.static(opts.webDist));
    app.get('/{*splat}', (_req, res) => res.sendFile('index.html', { root: opts.webDist! }));
  }
  app.use(errorHandler);

  return {
    app,
    service,
    db,
    prisma,
    registry,
    async close() {
      await db.destroy();
      await prisma.$disconnect();
    },
  };
}
