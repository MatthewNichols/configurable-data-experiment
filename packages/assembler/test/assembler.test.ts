import { describe, expect, it } from 'vitest';
import { defineModule } from '@cde/sdk';
import { AssemblyError, buildRegistry, entityPrisma, extrasSql, loadCustomer, type LoadedCustomer } from '../src/index.ts';

const customer = (modules: LoadedCustomer['modules']): LoadedCustomer => ({
  config: { name: 't', title: 'T', modules: modules.map((m) => m.ref) },
  dir: '/tmp',
  modules,
});
const mod = (manifest: Parameters<typeof defineModule>[0]) => ({ manifest, dir: '/tmp', ref: manifest.name });

describe('registry validation', () => {
  it('rejects colliding module names, bad types, unknown entities and refs', () => {
    const c = customer([
      mod({ name: 'loyalty', extends: { Customer: { fields: { tier: { type: 'enum' } as any } } } }),
      mod({ name: 'loyalty', extends: { Customer: { fields: { other: { type: 'string' } } } } }),
      mod({ name: 'Bad-Name' }),
      mod({ name: 'x', extends: { Boat: { fields: {} }, Car: { fields: { owner: { type: 'reference', ref: 'Person' }, n: { type: 'money' as any } } } } }),
      mod({ name: 'y', extends: { Car: { fields: { s: { type: 'string', searchable: 'range' } }, filters: { due: { type: 'bool' } } } } }),
    ]);
    expect(() => buildRegistry(c)).toThrow(AssemblyError);
    try {
      buildRegistry(c);
    } catch (e) {
      expect((e as AssemblyError).problems).toEqual([
        'loyalty: Customer.tier: enum fields need "values"',
        'loyalty: module name "loyalty" is already used by loyalty (ext namespaces would collide)',
        'Bad-Name: module name "Bad-Name" must be camelCase (it is the JSONB namespace)',
        'x: extends unknown entity "Boat"',
        'x: Car.owner: reference to unknown entity "Person"',
        'x: Car.n: unknown field type "money"',
        'y: Car.s: "range" search needs an int, decimal or date field',
        'y: filter Car.due needs a server entry to implement it',
      ]);
    }
  });
});

describe('module entities', () => {
  const garage = { label: 'Garage', titleFields: ['name'], fields: { name: { type: 'string' as const, required: true } } };

  it('registers them after core, extensible and referenceable regardless of module order', () => {
    const registry = buildRegistry(
      customer([
        // listed before the module that declares Garage
        mod({ name: 'tools', extends: { Garage: { fields: { lifts: { type: 'int' } } }, Car: { fields: { garage: { type: 'reference', ref: 'Garage' } } } } }),
        mod({ name: 'fleet', entities: { Garage: garage } }),
      ]),
    );
    expect(registry.entityOrder).toEqual(['Customer', 'Car', 'Garage']);
    expect(registry.entities.Garage).toMatchObject({ path: 'garages', table: 'Garage', delegate: 'garage', module: 'fleet', pluralLabel: 'Garages' });
    expect(registry.entities.Garage.fields.map((f) => [f.key, f.source])).toEqual([
      ['name', 'core'],
      ['tools.lifts', 'ext'],
    ]);
    expect(registry.entities.Car.fields.find((f) => f.key === 'tools.garage')?.ref).toBe('Garage');
  });

  it('rejects bad names, collisions, reserved fields and paths', () => {
    const c = customer([
      mod({ name: 'a', entities: { Garage: garage, Car: garage, depot: { ...garage, label: 'Depot' } } }),
      mod({ name: 'b', entities: { Garage: garage, Shed: { ...garage, path: 'cars' }, Thing: { ...garage, path: 'api' } } }),
      mod({ name: 'c', entities: { Bay: { label: 'Bay', titleFields: ['nope'], fields: { id: { type: 'string' }, Size: { type: 'int' }, at: { type: 'reference', ref: 'Boat' } } } } }),
    ]);
    try {
      buildRegistry(c);
      expect.unreachable();
    } catch (e) {
      expect((e as AssemblyError).problems).toEqual([
        'a: entity "Car" is already declared by core',
        'a: entity name "depot" must be PascalCase',
        'b: entity "Garage" is already declared by a',
        'b: entity Shed path "cars" is already used by Car',
        'b: entity Thing path "api" is reserved',
        'c: entity Bay: titleFields "nope" is not one of its fields',
        'c: entity Bay: field name "id" is reserved',
        'c: entity Bay: field names must be camelCase ("Size")',
        'c: Bay.at: reference to unknown entity "Boat"',
      ]);
    }
  });

  it('generates a Prisma model shaped like the core ones', () => {
    const registry = buildRegistry(
      customer([
        mod({
          name: 'fleet',
          entities: {
            Garage: {
              ...garage,
              fields: {
                ...garage.fields,
                bays: { type: 'int' },
                rate: { type: 'decimal', required: true },
                opened: { type: 'date' },
                open: { type: 'bool' },
                manager: { type: 'reference', ref: 'Customer' },
              },
            },
          },
        }),
      ]),
    );
    expect(entityPrisma(registry.entities.Garage)).toMatchInlineSnapshot(`
      "// Generated by @cde/assembler from the fleet module's declaration of Garage — do not edit.
      model Garage {
        id           String                   @id @default(uuid()) @db.Uuid
        name         String
        bays         Int?
        rate         Decimal @db.Decimal(12, 2)
        opened       DateTime? @db.Date
        open         Boolean?
        manager      String? @db.Uuid
        ext          Json                     @default("{}")
        searchVector Unsupported("tsvector")?
        createdAt    DateTime                 @default(now())
        updatedAt    DateTime                 @updatedAt
        // @cde:extend Garage

        @@index([manager])
        @@index([ext(ops: JsonbPathOps)], type: Gin)
        @@index([searchVector], type: Gin)
      }
      "
    `);
  });
});

describe('customer builds', () => {
  for (const name of ['bare', 'acme', 'globex']) {
    it(`${name}: registry snapshot (catches accidental contract changes)`, async () => {
      const registry = buildRegistry(await loadCustomer(name));
      await expect(JSON.stringify(registry, null, 2)).toMatchFileSnapshot(`./__snapshots__/${name}.registry.json`);
    });
  }

  it('generates search-vector triggers that include module text fields', async () => {
    const registry = buildRegistry(await loadCustomer('globex'));
    const sql = extrasSql(registry, []);
    expect(sql).toContain(`NEW.ext #>> '{fleet,fleetNumber}'`);
    expect(sql).toContain(`NEW.ext #>> '{fleet,licenseNumber}'`);
  });
});
