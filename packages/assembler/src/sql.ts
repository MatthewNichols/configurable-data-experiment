import type { Registry, RegistryEntity, RegistryField } from '@cde/sdk';

const q = (id: string) => `"${id}"`;

function textExpr(f: RegistryField, row = 'NEW'): string {
  if (f.source === 'core') return f.type === 'string' || f.type === 'text' ? `${row}.${q(f.column!)}` : `${row}.${q(f.column!)}::text`;
  return `${row}.ext #>> '{${f.path![0]},${f.path![1]}}'`;
}

function entitySql(e: RegistryEntity): string {
  const t = q(e.table);
  const textFields = e.fields.filter((f) => f.source !== 'computed' && f.searchable.includes('text'));
  const vector = textFields.length ? `to_tsvector('simple', concat_ws(' ', ${textFields.map((f) => textExpr(f)).join(', ')}))` : 'NULL';
  const fn = q(`cde_${e.table}_search_vector`);
  const out = [
    `-- ${e.name}: full-text vector from fields marked searchable: 'text'`,
    `CREATE OR REPLACE FUNCTION ${fn}() RETURNS trigger LANGUAGE plpgsql AS $$`,
    `BEGIN`,
    `  NEW."searchVector" := ${vector};`,
    `  RETURN NEW;`,
    `END $$;`,
    `DROP TRIGGER IF EXISTS ${fn} ON ${t};`,
    `CREATE TRIGGER ${fn} BEFORE INSERT OR UPDATE ON ${t} FOR EACH ROW EXECUTE FUNCTION ${fn}();`,
  ];
  out.push(`-- re-run the trigger so existing rows pick up new searchable fields`);
  out.push(`UPDATE ${t} SET "searchVector" = NULL;`);
  return out.join('\n');
}

/** Must run before Prisma's DDL (trigram indexes in core.prisma need the extension). */
export const PRE_SQL = 'CREATE EXTENSION IF NOT EXISTS pg_trgm;\n';

/**
 * Idempotent SQL that Prisma cannot express (search-vector triggers, module SQL). Kept free
 * of indexes/columns so Prisma never sees it as schema drift. Appended to every generated
 * migration and applied after `db push` in tests.
 */
export function extrasSql(registry: Registry, moduleSql: { module: string; sql: string }[]): string {
  return [
    '-- >>> cde extras (generated by @cde/assembler; idempotent) >>>',
    ...registry.entityOrder.map((n) => entitySql(registry.entities[n])),
    ...moduleSql.map(({ module, sql }) => `-- module ${module}\n${sql.trim()}`),
    '-- <<< cde extras <<<',
    '',
  ].join('\n\n');
}
