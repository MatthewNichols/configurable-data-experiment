import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import type { Registry, RegistryField } from '@cde/sdk';
import { loadCustomer, type LoadedCustomer } from './load.ts';
import { relImport, repoRoot } from './paths.ts';
import { buildRegistry } from './registry.ts';
import { extrasSql } from './sql.ts';

export interface BuildResult {
  customer: LoadedCustomer;
  registry: Registry;
  outDir: string;
  extras: string;
  extrasHash: string;
}

export interface BuildOptions {
  outDir?: string;
  /** where committed migrations live; defaults to <customer>/prisma/migrations */
  migrationsDir?: string;
}

const HEADER = '// Generated by @cde/assembler — do not edit.\n';
const require = createRequire(import.meta.url);

function write(file: string, content: string) {
  mkdirSync(path.dirname(file), { recursive: true });
  writeFileSync(file, content);
}

function tsType(f: RegistryField): string {
  switch (f.type) {
    case 'int':
    case 'decimal':
      return 'number';
    case 'bool':
      return 'boolean';
    case 'enum':
      return f.values!.map((v) => JSON.stringify(v)).join(' | ');
    default:
      return 'string';
  }
}

function extTypes(registry: Registry): string {
  const out = [HEADER];
  for (const name of registry.entityOrder) {
    const byModule = new Map<string, string[]>();
    for (const f of registry.entities[name].fields) {
      if (f.source !== 'ext') continue;
      const [mod, key] = f.path!;
      if (!byModule.has(mod)) byModule.set(mod, []);
      byModule.get(mod)!.push(`    ${key}?: ${tsType(f)} | null;`);
    }
    out.push(`export interface ${name}Ext {`);
    for (const [mod, lines] of byModule) out.push(`  ${mod}?: {\n${lines.join('\n')}\n  };`);
    out.push('}\n');
  }
  return out.join('\n');
}

export async function buildCustomer(
  nameOrCustomer: string | LoadedCustomer,
  opts: BuildOptions = {},
): Promise<BuildResult> {
  const customer = typeof nameOrCustomer === 'string' ? await loadCustomer(nameOrCustomer) : nameOrCustomer;
  const registry = buildRegistry(customer);
  const outDir = opts.outDir ?? path.join(customer.dir, '.cde');
  rmSync(outDir, { recursive: true, force: true, maxRetries: 3 });
  // keep the generated Prisma client if a previous build left one? No: always regenerate for a clean build.
  mkdirSync(outDir, { recursive: true });

  write(path.join(outDir, 'registry.json'), JSON.stringify(registry, null, 2) + '\n');

  // --- Prisma schema folder: core model (with injected fields) + module fragments
  let core = readFileSync(require.resolve('@cde/core-server/prisma/core.prisma'), 'utf8');
  for (const { manifest: m } of customer.modules) {
    for (const [entity, ext] of Object.entries(m.extends ?? {})) {
      if (!ext.prismaFields?.length) continue;
      const marker = `// @cde:extend ${entity}`;
      const lines = ext.prismaFields.map((l) => `  ${l.trim()} // from module ${m.name}`).join('\n');
      core = core.replace(marker, `${lines}\n  ${marker}`);
    }
  }
  write(path.join(outDir, 'prisma', 'core.prisma'), core);
  for (const { manifest: m, dir } of customer.modules) {
    if (!m.prismaSchema) continue;
    write(path.join(outDir, 'prisma', `module.${m.name}.prisma`), readFileSync(path.resolve(dir, m.prismaSchema), 'utf8'));
  }
  const migrationsDir = opts.migrationsDir ?? path.join(customer.dir, 'prisma', 'migrations');
  write(
    path.join(outDir, 'prisma.config.ts'),
    `${HEADER}import { defineConfig } from 'prisma/config';

export default defineConfig({
  schema: './prisma',
  migrations: { path: ${JSON.stringify(relImport(outDir, migrationsDir))} },
  datasource: { url: process.env.DATABASE_URL ?? 'postgresql://unset:unset@localhost:5432/unset' },
});
`,
  );

  // --- SQL Prisma can't express
  const moduleSql = customer.modules
    .filter(({ manifest: m }) => m.sql)
    .map(({ manifest: m, dir }) => ({ module: m.name, sql: readFileSync(path.resolve(dir, m.sql!), 'utf8') }));
  const extras = extrasSql(registry, moduleSql);
  const extrasHash = createHash('sha256').update(extras).digest('hex');
  write(path.join(outDir, 'extras.sql'), extras);

  // --- static module indexes (no runtime discovery)
  const server = customer.modules.filter(({ manifest: m }) => m.server);
  write(
    path.join(outDir, 'server-modules.ts'),
    HEADER +
      server.map(({ manifest: m, dir }, i) => `import m${i} from '${relImport(outDir, path.resolve(dir, m.server!))}';`).join('\n') +
      `\nimport type { ServerModule } from '@cde/sdk/server';\n\nexport const serverModules: Record<string, ServerModule> = {\n` +
      server.map(({ manifest: m }, i) => `  ${m.name}: m${i},\n`).join('') +
      '};\n',
  );
  const web = customer.modules.filter(({ manifest: m }) => m.web);
  write(
    path.join(outDir, 'web-modules.ts'),
    HEADER +
      web.map(({ manifest: m, dir }, i) => `import m${i} from '${relImport(outDir, path.resolve(dir, m.web!))}';`).join('\n') +
      `\nimport type { WebModule } from '@cde/sdk/web';\n\nexport const webModules: Record<string, WebModule> = {\n` +
      web.map(({ manifest: m }, i) => `  ${m.name}: m${i},\n`).join('') +
      '};\n',
  );
  write(path.join(outDir, 'ext-types.ts'), extTypes(registry));

  write(
    path.join(outDir, 'install.ts'),
    `${HEADER}import { PrismaPg } from '@prisma/adapter-pg';
import { createInstall } from '@cde/core-server';
import type { Registry } from '@cde/sdk';
import { PrismaClient } from './prisma-client/client.ts';
import registryJson from './registry.json' with { type: 'json' };
import { serverModules } from './server-modules.ts';

export const registry = registryJson as unknown as Registry;

export function install(databaseUrl: string, webDist?: string) {
  const prisma = new PrismaClient({ adapter: new PrismaPg({ connectionString: databaseUrl }) });
  return createInstall({ registry, prisma, databaseUrl, modules: serverModules, webDist });
}
`,
  );
  const seedFile = path.join(customer.dir, 'seed.ts');
  write(
    path.join(outDir, 'main.ts'),
    `${HEADER}import { fileURLToPath } from 'node:url';
import { runSeed } from '@cde/core-server';
import { install } from './install.ts';

const url = process.env.DATABASE_URL;
if (!url) throw new Error('DATABASE_URL is not set');
const cmd = process.argv[2] ?? 'serve';
const inst = await install(url, fileURLToPath(new URL('./web-dist', import.meta.url)));

if (cmd === 'seed') {
${
  existsSync(seedFile)
    ? `  const { default: seed } = await import('${relImport(outDir, seedFile)}');
  console.log((await runSeed(inst, seed)) ? 'Seeded demo data' : 'Database not empty; skipping seed');`
    : `  console.log('No seed.ts for this customer');`
}
  await inst.close();
} else {
  const port = Number(process.env.PORT ?? 3000);
  inst.app.listen(port, () => console.log(\`${customer.config.title} listening on :\${port}\`));
}
`,
  );

  return { customer, registry, outDir, extras, extrasHash };
}

export const prismaBin = path.join(repoRoot, 'node_modules', '.bin', 'prisma');
