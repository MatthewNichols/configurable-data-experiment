import type { RegistryEntity, RegistryField } from '@cde/sdk';

function columnType(f: RegistryField): string {
  switch (f.type) {
    case 'int':
      return 'Int';
    case 'decimal':
      return 'Decimal @db.Decimal(12, 2)';
    case 'bool':
      return 'Boolean';
    case 'date':
      return 'DateTime @db.Date';
    case 'reference':
      return 'String @db.Uuid';
    default:
      return 'String';
  }
}

/**
 * Prisma model for a module-declared entity. Same shape as the core models (uuid id, `ext`,
 * `searchVector`, timestamps) so EntityService, search and the extras SQL treat it like core.
 * References are plain indexed uuid columns (no Prisma relation); EntityService checks them.
 */
export function entityPrisma(entity: RegistryEntity): string {
  const own = entity.fields.filter((f) => f.source === 'core');
  const width = Math.max(12, ...own.map((f) => f.column!.length));
  const line = (name: string, type: string) => `  ${name.padEnd(width)} ${type}`;
  const optional = (f: RegistryField) => (f.required ? '' : '?');
  const columns = own.map((f) => {
    const [base, ...attrs] = columnType(f).split(' ');
    return line(f.column!, [base + optional(f), ...attrs].join(' '));
  });
  const indexes = own.filter((f) => f.type === 'reference').map((f) => `  @@index([${f.column}])`);
  return [
    `// Generated by @cde/assembler from the ${entity.module} module's declaration of ${entity.name} — do not edit.`,
    `model ${entity.table} {`,
    line('id', 'String                   @id @default(uuid()) @db.Uuid'),
    ...columns,
    line('ext', 'Json                     @default("{}")'),
    line('searchVector', 'Unsupported("tsvector")?'),
    line('createdAt', 'DateTime                 @default(now())'),
    line('updatedAt', 'DateTime                 @updatedAt'),
    `  // @cde:extend ${entity.name}`,
    '',
    ...indexes,
    '  @@index([ext(ops: JsonbPathOps)], type: Gin)',
    '  @@index([searchVector], type: Gin)',
    '}',
    '',
  ].join('\n');
}
